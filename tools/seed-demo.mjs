// ── geometry ──────────────────────────────────────────────────

const R = 6371000;
const rad = (d) => (d * Math.PI) / 180;
function distanceM(aLat, aLng, bLat, bLng) {
  const dLat = rad(bLat - aLat), dLng = rad(bLng - aLng);
  const s = Math.sin(dLat / 2) ** 2 +
    Math.cos(rad(aLat)) * Math.cos(rad(bLat)) * Math.sin(dLng / 2) ** 2;
  return 2 * R * Math.asin(Math.sqrt(s));
}

/**
 * Evenly spaced points along a polyline, about `stepM` apart.
 *
 * A RESAMPLER, not a densifier. The earlier version only ever inserted
 * points between the source points, which was fine for a five-point
 * hand-drawn line and wrong for road geometry: OSRM emits vertices at every
 * kink, sometimes a metre apart, and subdividing those gave a "route"
 * whose fixes were 0 m apart — failing the 40 m displacement bar that the
 * whole 80 m sampling exists to clear.
 *
 * Spacing is uniform at total/n rather than exactly stepM, so the final
 * point lands on the destination instead of a stub segment shorter than the
 * rest.
 */
function resample(route, stepM) {
  const cum = [0];
  for (let i = 1; i < route.length; i++) {
    cum[i] = cum[i - 1] + distanceM(...route[i - 1], ...route[i]);
  }
  const total = cum[cum.length - 1];
  if (total <= 0) return [route[0], route[route.length - 1]];

  const n = Math.max(1, Math.round(total / stepM));
  const out = [];
  let seg = 1;
  for (let k = 0; k <= n; k++) {
    const target = (total * k) / n;
    while (seg < cum.length - 1 && cum[seg] < target) seg++;
    const a = route[seg - 1], b = route[seg];
    const segLen = cum[seg] - cum[seg - 1];
    const f = segLen <= 0 ? 0 : (target - cum[seg - 1]) / segLen;
    out.push([a[0] + (b[0] - a[0]) * f, a[1] + (b[1] - a[1]) * f]);
  }
  return out;
}

const insidePlace = (lat, lng) =>
  PLACES.some((p) => distanceM(lat, lng, p.lat, p.lng) <= p.radius_m);

const reverse = (route) => [...route].reverse();

/**
 * One trip's breadcrumbs. Points inside a place are dropped rather than
 * shifted — that is what the device does, and it is what makes History show
 * a stay followed by a trip instead of one continuous smear.
 */
function trip(route, startMs, speedMs, { stepM = 25, jitterM = 4 } = {}) {
  const pts = resample(route, stepM);
  const rows = [];
  let t = startMs;
  for (let i = 0; i < pts.length; i++) {
    if (i > 0) t += (distanceM(...pts[i - 1], ...pts[i]) / speedMs) * 1000;
    const [lat, lng] = pts[i];
    if (insidePlace(lat, lng)) continue;
    // Jitter is small on purpose. The geometry is road-snapped now, and
    // scattering it more than a lane's width would undo that by putting
    // breadcrumbs through front gardens.
    const jLat = (Math.random() - 0.5) * (jitterM / 111000) * 2;
    const jLng = (Math.random() - 0.5) * (jitterM / 88000) * 2;
    rows.push({
      lat: +(lat + jLat).toFixed(6),
      lng: +(lng + jLng).toFixed(6),
      speed: +(speedMs * (0.85 + Math.random() * 0.3)).toFixed(2),
      at: new Date(t),
    });
  }
  // `t` has run past every point, including the suppressed tail inside the
  // destination — so it is when the traveller actually got there, which is
  // what the arrival check-in should say. Deriving it beats a hardcoded
  // clock time that silently stops matching the route the moment the route
  // changes length.
  return { rows, endMs: t };
}

// ── the day plan (pure — no network) ──────────────────────────

function buildPlan() {
  for (const m of MEMBERS) m.id = crypto.randomUUID();
  for (const p of PLACES) p.id = crypto.randomUUID();

  const DAY = 86400000;
  const midnight = (offset) => {
    const d = new Date();
    d.setHours(0, 0, 0, 0);
    return d.getTime() - offset * DAY;
  };
  const at = (offset, h, min) => midnight(offset) + h * 3600000 + min * 60000;

  const breadcrumbs = [], checkins = [], arrived = {};

  // Nothing may be stamped in the future. Seeding at 07:00 would otherwise
  // file an 08:05 school run that has not happened, and the History tab
  // would show a trip ahead of the clock. Truncating instead of shifting
  // also gives a run mid-morning a genuinely in-progress trip.
  const now = Date.now();
  const checkin = (member, place, type, ms) => {
    if (ms > now) return;
    checkins.push({ member, place, type, at: new Date(ms) });
    if (type === 'arrived') arrived[member.key] = { place, at: new Date(ms) };
  };
  const record = (member, rows) => {
    for (const r of rows) if (r.at.getTime() <= now) breadcrumbs.push({ member, ...r });
  };

  /**
   * One complete journey: left A, a trail, arrived B.
   *
   * The arrival time comes from the trip itself rather than a hardcoded
   * clock time. With road geometry the legs are whatever length the roads
   * make them, and a fixed "arrived at 08:18" would quietly stop matching
   * the trail the moment a place moved.
   *
   * @return the arrival time, so the caller can schedule what follows.
   */
  const journey = (member, route, startMs, speedMs, fromPlace, toPlace) => {
    checkin(member, fromPlace, 'left', startMs);
    const { rows, endMs } = trip(route, startMs, speedMs);
    record(member, rows);
    if (toPlace) checkin(member, toPlace, 'arrived', endMs);
    return endMs;
  };

  // The two previous days are a routine on the clock: out in the morning,
  // back in the afternoon.
  const DRIVE_MS = 11, DRIVE_HOME_MS = 10.5, WALK_MS = 1.35, WALK_HOME_MS = 1.3;
  for (let d = 2; d >= 1; d--) {
    journey(M.child, ROUTE_SCHOOL, at(d, 8, 5), DRIVE_MS, P.home, P.school);
    journey(M.child, reverse(ROUTE_SCHOOL), at(d, 15, 30), DRIVE_HOME_MS, P.school, P.home);

    const shopped = journey(M.adult, ROUTE_SHOPS, at(d, 10, 15), WALK_MS, P.home, P.shops);
    // Twenty-five minutes in the shop, then home — scheduled off the actual
    // arrival so the stay is a stay and not an overlap.
    journey(M.adult, reverse(ROUTE_SHOPS), shopped + 25 * 60000, WALK_HOME_MS, P.shops, P.home);
  }

  // Today is anchored to NOW, not to the clock. Fixed morning slots would
  // leave a demo seeded in the evening showing a family that has not moved
  // for nine hours, and a demo seeded before breakfast showing nothing at
  // all. Relative offsets give a live-looking map whenever it is run.
  const ago = (mins) => now - mins * 60000;

  // Child drove to school a while back and is still there. Started far
  // enough back that the whole leg has finished whatever the route length.
  journey(M.child, ROUTE_SCHOOL, ago(95), DRIVE_MS, P.home, P.school);

  // Adult is still walking — no destination passed, so no arrival check-in,
  // and record() truncates the trail at now. That leaves one member visibly
  // in motion with a live trail behind them, which is the state worth
  // photographing.
  journey(M.adult, ROUTE_SHOPS, ago(8), WALK_MS, P.home, null);

  breadcrumbs.sort((a, b) => a.at - b.at);
  checkins.sort((a, b) => a.at - b.at);

  /**
   * Where each member's map pin sits.
   *
   * Not simply "the last breadcrumb": a trip that ends at a place has its
   * final points suppressed inside the radius, so the last breadcrumb is
   * always on the boundary — every arrived member would be pinned to the
   * edge of their own garden. An arrival check-in that is NEWER than the
   * last breadcrumb is the signal that the journey finished, and it wins.
   */
  const RECENT_MS = 2 * 3600000;
  const pin = (m) => {
    const mine = breadcrumbs.filter((b) => b.member.key === m.key);
    const last = mine[mine.length - 1];
    const a = arrived[m.key];
    const stillOut = last && now - last.at.getTime() < RECENT_MS &&
      (!a || a.at.getTime() < last.at.getTime());
    if (stillOut) return { lat: last.lat, lng: last.lng, seen: last.at };
    const p = a ? a.place : P.home;
    // A few metres off centre, or three members stack into one dot.
    const off = (n) => (((m.key.charCodeAt(0) * n) % 7) - 3) * 0.00015;
    return {
      lat: +(p.lat + off(3)).toFixed(6),
      lng: +(p.lng + off(5)).toFixed(6),
      seen: a ? a.at : new Date(now - 15 * 60000),
    };
  };
  return { breadcrumbs, checkins, pin };
}

/**
 * app.js tripStats/segmentTrips, close enough to check what will render.
 *
 * "Close enough" has to include the EMISSION filter, or the dry run asserts
 * something the app does not do. It used to skip even TRIP_MIN_M; now that
 * app.js also requires a trip to have gone somewhere (spanM) and splits on a
 * stationary stretch as well as a silence, this mirrors both. If it drifts
 * from app.js again, the dry run goes back to quietly blessing seeds the
 * timeline will refuse to show.
 */
const TRIP_MIN_M = 120;
const TRIP_SPAN_MIN_M = 120;
const STILL_RADIUS_M = 120;
const STILL_WINDOW_MS = 15 * 60 * 1000;
function classify(rows) {
  const trips = [];
  let cur = null, lastT = null, anchor = null;
  for (const p of rows) {
    const t = p.at.getTime();
    const gap = !!(cur && lastT != null && t - lastT > TRIP_GAP_MS);
    if (!gap && anchor) {
      if (distanceM(anchor.lat, anchor.lng, p.lat, p.lng) > STILL_RADIUS_M) {
        anchor = { lat: p.lat, lng: p.lng, t };
      } else if (t - anchor.t > STILL_WINDOW_MS) {
        cur = null; continue;
      }
    }
    if (!cur || gap) { cur = []; trips.push(cur); anchor = { lat: p.lat, lng: p.lng, t }; }
    cur.push(p); lastT = t;
  }
  return trips.filter((t) => t.length >= 2).map((t) => {
    let distM = 0, spanM = 0, maxSp = 0, sum = 0;
    for (let i = 1; i < t.length; i++) distM += distanceM(t[i - 1].lat, t[i - 1].lng, t[i].lat, t[i].lng);
    for (const p of t) spanM = Math.max(spanM, distanceM(t[0].lat, t[0].lng, p.lat, p.lng));
    for (const p of t) { maxSp = Math.max(maxSp, p.speed); sum += p.speed; }
    const avgSp = sum / t.length;
    const mode = (avgSp >= DRIVE_AVG_MS || maxSp >= DRIVE_MAX_MS) ? 'drive'
               : (avgSp >= RIDE_AVG_MS) ? 'ride' : 'walk';
    return { mode, distM, spanM, avgSp, n: t.length, start: t[0].at };
  }).filter((t) => t.distM >= TRIP_MIN_M && t.spanM >= TRIP_SPAN_MIN_M);
}

