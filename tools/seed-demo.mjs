#!/usr/bin/env node
//
// Seed the Play-review demo backend with an invented family.
//
//   node tools/seed-demo.mjs --ref <ref> --dry-run     # plan only, no network
//
//   $env:SUPABASE_ACCESS_TOKEN = "sbp_..."             # PowerShell
//   node tools/seed-demo.mjs --ref <demo-project-ref>
//
// WHY THIS EXISTS
// ---------------
// Play's "App access" field needs a reviewer to be able to USE the app, and
// Roamkeep cannot be used without a backend — a reviewer cannot provision a
// Supabase project. So one demo project exists purely for review.
//
// It must not be seeded from real devices. Doing that would put the author's
// home, school and daily movements into a database whose credentials are
// handed to Google and printed in a store listing. Everything here is
// invented: three fictional members, three places in Mountain View, and
// trails computed from a polyline.
//
// WHAT MAKES THE DATA LOOK REAL
// -----------------------------
// Naive seeding produces a History tab that renders wrong, because the app
// reconstructs a day from two different signals:
//
//   • STAYS come from arrived/left checkin PAIRS — never from breadcrumbs,
//     because the native writer suppresses breadcrumbs inside a saved place
//     (LocationUpdateReceiver.processLocations). So this omits any generated
//     point falling inside a place radius, exactly like the real writer.
//   • TRIPS come from breadcrumbs, split on a gap longer than TRIP_GAP_MS
//     (10 min) and classified walk/ride/drive from GPS speed (DRIVE_AVG_MS
//     8, RIDE_AVG_MS 2.2). The speeds below straddle those thresholds on
//     purpose, and --dry-run re-runs the app's own classifier to prove it.
//
// SAFETY
// ------
// This DELETES every member, place, checkin and breadcrumb in the target
// project before re-seeding. Two interlocks stop that reaching a real
// family: a refusal list of known-real refs, and a check that the project
// contains no keep other than this script's own demo keep.
//
// Re-run before submitting — location_history is pruned at 7 days, so a demo
// seeded a fortnight before review shows an empty History tab. Do NOT re-run
// while a review is in progress: member ids are regenerated, which
// invalidates a session the reviewer has already established.

