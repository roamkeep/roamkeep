/**
 * Routes for a mock-location player, in both formats worth having.
 *
 * GPX carries a <time> per point, so a player that steps point-to-point
 * (the Android emulator does) gets its pacing from the file. KML is a bare
 * LineString with no timing at all — several mock apps only import KML, and
 * they interpolate along the path at a speed you set in their UI.
 *
 * Points are 80 m apart. That matters only for a player that does NOT
 * interpolate: each delivered fix must clear the 40 m displacement bar in
 * LocationForegroundService.detectMoving, because a mocked fix often carries
 * no speed and displacement is then the only evidence of motion. A route
 * sampled every 15 m can read as a stationary device, and the trail never
 * densifies. For an interpolating player the spacing is merely cosmetic.
 */
// 110 m rather than the 40 m bar, because the bar applies to STRAIGHT-LINE
// displacement between consecutive fixes and these points are spaced along
// the ARC. At a right-angle turn the straight-line gap is much shorter than
// the arc between the same two points — 80 m sampling measured 43 m at the
// tightest corner, passing by 3 m. 110 m leaves real margin.
const ROUTE_STEP_M = 110;
const ROUTE_STEP_MS = 8000;  // 110 m / 8 s ≈ 50 km/h — urban, not motorway
const ROUTE_EPOCH = Date.parse('2026-01-01T09:00:00Z');

function writeRoute(slug, title, route) {
  const pts = resample(route, ROUTE_STEP_M);
  const gpx = path.join(OUT, `${slug}.gpx`);
  const kml = path.join(OUT, `${slug}.kml`);

  fs.writeFileSync(gpx, `<?xml version="1.0" encoding="UTF-8"?>
<gpx version="1.1" creator="roamkeep-seed-demo" xmlns="http://www.topografix.com/GPX/1/1">
  <trk><name>${title}</name><trkseg>
${pts.map(([lat, lng], i) =>
    `    <trkpt lat="${lat.toFixed(6)}" lon="${lng.toFixed(6)}">` +
    `<time>${new Date(ROUTE_EPOCH + i * ROUTE_STEP_MS).toISOString()}</time></trkpt>`).join('\n')}
  </trkseg></trk>
</gpx>
`);

  fs.writeFileSync(kml, `<?xml version="1.0" encoding="UTF-8"?>
<kml xmlns="http://www.opengis.net/kml/2.2"><Document><name>${title}</name>
  <Placemark><name>${title}</name><LineString><tessellate>1</tessellate>
    <coordinates>
${pts.map(([lat, lng]) => `      ${lng.toFixed(6)},${lat.toFixed(6)},0`).join('\n')}
    </coordinates>
  </LineString></Placemark>
</Document></kml>
`);

  let min = Infinity, total = 0;
  for (let i = 1; i < pts.length; i++) {
    const d = distanceM(...pts[i - 1], ...pts[i]);
    min = Math.min(min, d); total += d;
  }
  return { slug, pts: pts.length, min, km: total / 1000, gpx, kml };
}

