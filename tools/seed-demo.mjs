/**
 * Projects that must never be seeded, because seeding WIPES the target.
 *
 * These used to be hardcoded, which named the author's own family database
 * in a repository that is about to be published. A Supabase ref is not a
 * secret — the anon key is public by design and RLS is the actual boundary —
 * but printing a real household's endpoint in a public file invites people
 * to go and test that boundary, for no benefit to anyone.
 *
 * So the list is assembled from sources that are gitignored:
 *
 *   • deploy.config.json's url — the owner's own backend, already on this
 *     machine and already excluded from git.
 *   • an optional `neverSeed` array in that same file, for anything else
 *     that has had real devices on it.
 *   • ROAMKEEP_NEVER_SEED, comma-separated, for a one-off.
 *
 * If none of those exist the list is empty, and the interlock further down —
 * refusing any project that holds a keep this script did not create — is the
 * one doing the work. That one needs no configuration and is the reason a
 * fresh clone is still safe.
 */
function refusalList() {
  const never = new Map();
  try {
    const cfg = JSON.parse(fs.readFileSync(path.join(REPO, 'deploy.config.json'), 'utf8'));
    const m = /https:\/\/([a-z0-9]+)\.supabase\.co/i.exec(cfg.url || '');
    if (m) never.set(m[1], "the project in deploy.config.json — the owner's own backend");
    for (const r of cfg.neverSeed || []) {
      never.set(String(r).trim(), 'listed in deploy.config.json neverSeed');
    }
  } catch { /* no deploy config on this machine — fine */ }
  for (const r of (process.env.ROAMKEEP_NEVER_SEED || '').split(',')) {
    if (r.trim()) never.set(r.trim(), 'listed in ROAMKEEP_NEVER_SEED');
  }
  return never;
}
