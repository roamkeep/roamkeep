#!/usr/bin/env node
//
// Fetch road-snapped geometry for the demo routes and cache it in the repo.
//
//   node tools/fetch-demo-routes.mjs
//
// WHY THIS IS A SEPARATE SCRIPT
// -----------------------------
// The seeder used hand-picked waypoints, so its trails cut diagonally across
// blocks and through buildings — obviously synthetic on a map, which is the
// one thing demo data must not be.
//
// This asks a public routing service for geometry that follows actual roads,
// and writes the answer to tools/demo-routes.json, which IS COMMITTED. The
// seeder then reads that file and never touches the network, so
// `seed-demo.mjs --dry-run` still works offline and produces the same trails
// on every machine. Re-run this only to change a place or add a route.
//
// ⚠ THE PUBLIC OSRM SERVER ONLY HAS THE CAR PROFILE.
// Requesting /foot/ or /walking/ returns byte-identical geometry to
// /driving/ — verified, not assumed. So the "walk" route follows roads
// rather than footpaths, and may take a turn a pedestrian would not. Good
// enough for a demo; do not describe it as a pedestrian route.
//
// Everything here is invented demo geography in Mountain View. No real
// person's location is sent anywhere.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(HERE, 'demo-routes.json');

// Real, findable places, so a reviewer who checks a coordinate lands
// somewhere that makes sense. HOME is fixed: it is the Android emulator's
// default position, which is what lets a stock emulator open the app already
// inside a saved place.
const PLACES = {
  home:   { name: 'Home',   icon: '🏠', lat: 37.42200, lng: -122.08410, radius_m: 150,
            note: 'Android emulator default position, beside Charleston Park' },
  school: { name: 'School', icon: '🏫', lat: 37.41066, lng: -122.08548, radius_m: 130,
            note: 'Crittenden Middle School, 1701 Rock Street' },
  shops:  { name: 'Shops',  icon: '🛒', lat: 37.40312, lng: -122.07931, radius_m: 120,
            note: 'Safeway, 570 North Shoreline Boulevard' },
};

const ROUTES = [
  { key: 'drive', from: 'home', to: 'school', profile: 'driving' },
  { key: 'walk',  from: 'home', to: 'shops',  profile: 'driving' },
];

const OSRM = 'https://router.project-osrm.org/route/v1';

async function fetchRoute(r) {
  const a = PLACES[r.from], b = PLACES[r.to];
  const url = `${OSRM}/${r.profile}/${a.lng},${a.lat};${b.lng},${b.lat}` +
              '?overview=full&geometries=geojson';
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${r.key}: HTTP ${res.status}`);
  const j = await res.json();
  if (j.code !== 'Ok' || !j.routes?.length) throw new Error(`${r.key}: ${j.code} ${j.message || ''}`);
  const route = j.routes[0];
  return {
    key: r.key,
    from: r.from,
    to: r.to,
    profile: r.profile,
    distanceM: Math.round(route.distance),
    durationS: Math.round(route.duration),
    // OSRM gives [lng, lat]; store [lat, lng] to match every other
    // coordinate pair in this project and remove one chance to swap them.
    coords: route.geometry.coordinates.map(([lng, lat]) => [+lat.toFixed(6), +lng.toFixed(6)]),
  };
}

const R = 6371000;
const rad = (d) => (d * Math.PI) / 180;
function distanceM(aLat, aLng, bLat, bLng) {
  const dLat = rad(bLat - aLat), dLng = rad(bLng - aLng);
  const s = Math.sin(dLat / 2) ** 2 +
    Math.cos(rad(aLat)) * Math.cos(rad(bLat)) * Math.sin(dLng / 2) ** 2;
  return 2 * R * Math.asin(Math.sqrt(s));
}

const routes = {};
for (const r of ROUTES) {
  const got = await fetchRoute(r);

  // A route that does not start and end at the places it claims to join
  // would put the trail on the wrong street entirely. OSRM snaps to the
  // nearest road, so some offset is expected — a lot of it is a bug.
  const a = PLACES[r.from], b = PLACES[r.to];
  const startOff = distanceM(a.lat, a.lng, ...got.coords[0]);
  const endOff = distanceM(b.lat, b.lng, ...got.coords[got.coords.length - 1]);
  if (startOff > 250 || endOff > 250) {
    throw new Error(`${r.key}: snapped ${Math.round(startOff)} m from ${r.from} and ` +
      `${Math.round(endOff)} m from ${r.to} — check the coordinates.`);
  }

  routes[r.key] = got;
  console.log(`  ${r.key.padEnd(6)} ${r.from} -> ${r.to}  ` +
    `${(got.distanceM / 1000).toFixed(2)} km, ${got.coords.length} points, ` +
    `snapped ${Math.round(startOff)}/${Math.round(endOff)} m from the endpoints`);
  await new Promise((s) => setTimeout(s, 600));   // be polite to a free service
}

fs.writeFileSync(OUT, JSON.stringify({
  _README: 'Generated by tools/fetch-demo-routes.mjs. Committed on purpose so ' +
           'tools/seed-demo.mjs needs no network and every machine produces the ' +
           'same trails. Coordinates are [lat, lng]. Invented demo geography only.',
  _WARNING: 'The public OSRM server only has the car profile; a request for /foot/ ' +
            'returns identical geometry to /driving/. The "walk" route therefore ' +
            'follows roads, not footpaths.',
  source: 'https://router.project-osrm.org — OpenStreetMap data, ODbL',
  generated: new Date().toISOString(),
  places: PLACES,
  routes,
}, null, 2) + '\n');

console.log(`\n  written ${path.relative(path.join(HERE, '..'), OUT)}`);
